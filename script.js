let currentLang = "es";

function setLanguage(lang) {
  const dict = translations[lang] || translations.es;
  currentLang = lang in translations ? lang : "es";
  document.documentElement.lang = currentLang;
  document.title = dict.page_title;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = dict[el.dataset.i18n];
    if (v) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const v = dict[el.dataset.i18nAria];
    if (v) el.setAttribute("aria-label", v);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const v = dict[el.dataset.i18nAlt];
    if (v) el.setAttribute("alt", v);
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === currentLang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  renderTags();
}

/* ---------- Carrusel ---------- */
const carousel = document.querySelector(".carousel");
const track = carousel.querySelector(".track");
const slides = [...track.children];
const tagsBox = carousel.querySelector(".slide-tags");
const bar = document.querySelector(".progress-bar");
let index = 0;

function renderTags() {
  const tags = slideTags[currentLang][index] || [];
  tagsBox.innerHTML = "";
  tags.forEach((t) => {
    const s = document.createElement("span");
    s.textContent = t;
    tagsBox.appendChild(s);
  });
}

function update() {
  const slide = slides[index];
  const center = carousel.clientWidth / 2;
  const offset = slide.offsetLeft + slide.offsetWidth / 2;
  track.style.transform = `translateX(${center - offset}px)`;
  slides.forEach((s, i) => {
    s.classList.toggle("is-active", i === index);
    s.classList.toggle("is-near", Math.abs(i - index) === 1);
  });
  bar.style.width = `${((index + 1) / slides.length) * 100}%`;
  renderTags();
}

function go(i) {
  index = (i + slides.length) % slides.length;
  update();
}

document.querySelectorAll(".carousel-ctrl [data-dir]").forEach((btn) => {
  btn.addEventListener("click", () => go(index + Number(btn.dataset.dir)));
});

slides.forEach((s, i) => {
  s.querySelector(".slide-card").addEventListener("click", (e) => {
    if (i !== index) {
      e.preventDefault();
      go(i);
    }
  });
});

window.addEventListener("resize", update);

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

go(2);
